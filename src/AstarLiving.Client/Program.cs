using System.Windows;
using Velopack;

namespace AstarLiving.Client;

/// <summary>
/// จุดเริ่มของโปรแกรม
///
/// เขียน Main เองแทนที่จะให้ WPF สร้างให้ เพราะตัวอัปเดต Velopack
/// ต้องได้ทำงานเป็นสิ่งแรกสุดก่อนที่หน้าต่างใด ๆ จะถูกสร้าง
/// (ตอนติดตั้งหรืออัปเดต มันจะรันโปรแกรมพร้อมพารามิเตอร์พิเศษแล้วปิดตัวเองทันที
/// ถ้าโผล่หน้าต่างก่อน ผู้ใช้จะเห็นหน้าต่างกะพริบขึ้นมาระหว่างอัปเดต)
/// </summary>
public static class Program
{
    [STAThread]
    public static int Main(string[] args)
    {
        // ต้องเป็นสิ่งแรกสุดเสมอ
        //
        // ตอนติดตั้งหรืออัปเดต Velopack จะรันไฟล์นี้พร้อมพารามิเตอร์พิเศษ
        // (เช่น --veloapp-install) แล้วคาดหวังให้โปรแกรมทำงานนั้นแล้วปิดตัวเองทันที
        // ถ้าปล่อยให้โค้ดอื่นทำงานก่อน ผู้ใช้จะเห็นหน้าต่างกะพริบขึ้นมาระหว่างอัปเดต
        // และการสร้างทางลัดบนเดสก์ท็อปจะไม่เกิดขึ้น
        VelopackApp.Build().Run();

        var app = new App();
        app.InitializeComponent();

        return app.Run();
    }
}
